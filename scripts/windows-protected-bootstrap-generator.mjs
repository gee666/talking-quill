import { gzipSync } from 'node:zlib';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
export const protectedBootstrapSourcePath = resolve(
  repositoryRoot,
  'build',
  'windows-protected-bootstrap.ps1',
);
export const protectedBootstrapIncludePath = resolve(
  repositoryRoot,
  'build',
  'windows-protected-bootstrap-encoded.nsh',
);

export function canonicalizeProtectedBootstrapSource(source) {
  const text = Buffer.isBuffer(source) ? source.toString('utf8') : source;
  if (text.includes('\uFFFD')) throw new Error('Protected bootstrap source is not valid UTF-8');
  return text.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
}

export function renderProtectedBootstrapInclude(source) {
  const canonical = Buffer.from(canonicalizeProtectedBootstrapSource(source), 'utf8');
  const compressed = gzipSync(canonical, { level: 9, mtime: 0 });
  compressed.fill(0, 4, 8);
  compressed[9] = 255;
  const payload = compressed.toString('base64');
  return `; Generated by scripts/windows-protected-bootstrap-generator.mjs --write.\n; The payload is static. Never append installer arguments after PowerShell -Command.\n!define TALKING_QUILL_PROTECTED_BOOTSTRAP_PAYLOAD "${payload}"\n`;
}

export async function checkProtectedBootstrapInclude({
  sourcePath = protectedBootstrapSourcePath,
  includePath = protectedBootstrapIncludePath,
} = {}) {
  const [source, actual] = await Promise.all([readFile(sourcePath), readFile(includePath, 'utf8')]);
  const expected = renderProtectedBootstrapInclude(source);
  if (actual !== expected) {
    throw new Error(
      'Static protected bootstrap payload is stale. Run pnpm nsis:bootstrap:write and review both files.',
    );
  }
  return expected;
}

export async function writeProtectedBootstrapInclude({
  sourcePath = protectedBootstrapSourcePath,
  includePath = protectedBootstrapIncludePath,
} = {}) {
  const source = await readFile(sourcePath);
  const rendered = renderProtectedBootstrapInclude(source);
  await writeFile(includePath, rendered, 'utf8');
  return rendered;
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const [mode, ...extra] = process.argv.slice(2);
  if (extra.length !== 0 || !['--check', '--write'].includes(mode ?? '')) {
    throw new Error('Usage: windows-protected-bootstrap-generator.mjs <--check|--write>');
  }
  if (mode === '--write') await writeProtectedBootstrapInclude();
  else await checkProtectedBootstrapInclude();
}
